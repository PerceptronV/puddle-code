import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

/** Bundle the actual wrappers/import loader into a portable, client-bundled test kit. */
export async function huddleTestingFiles(root) {
  const outdir = join(root, '.huddle-testing-output');
  const result = await build({
    entryPoints: Object.fromEntries(
      ['run', 'worker', 'sdk'].map((name) => [
        name,
        join(root, `packages/daemon/src/huddle/testing/${name}.ts`),
      ]),
    ),
    outdir,
    write: false,
    bundle: true,
    splitting: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    minify: true,
    outExtension: { '.js': '.mjs' },
    chunkNames: 'chunks/[name]-[hash]',
    external: ['zod'],
    alias: { '@puddle/shared': join(root, 'packages/shared/src/index.ts') },
    // The shared entry point also exports the kit. Its generated bytes are not an
    // input to their own build (even unused strings affect minifier naming).
    plugins: [
      {
        name: 'exclude-generated-testing-assets',
        setup(build) {
          build.onLoad({ filter: /shared\/src\/huddle\/authoring\/testing\.ts$/ }, () => ({
            contents: 'export const huddleTestingAssets = {};',
            loader: 'ts',
          }));
        },
      },
    ],
  });
  const files = Object.fromEntries(
    result.outputFiles.map((file) => {
      if (file.contents.length > 256 * 1024)
        throw new Error('Testing asset exceeds the portable file limit');
      return ['testing/' + relative(outdir, file.path), file.text];
    }),
  );
  const zod = JSON.parse(
    await readFile(join(root, 'packages/daemon/node_modules/zod/package.json'), 'utf8'),
  );
  files['testing/package.json'] =
    JSON.stringify(
      {
        private: true,
        type: 'module',
        engines: { node: '>=22.15.0' },
        dependencies: { zod: zod.version },
      },
      null,
      2,
    ) + '\n';
  return files;
}
