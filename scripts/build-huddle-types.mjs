import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';
import { huddleAuthoringTypes } from './lib/huddle/types.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const target = new URL('../packages/shared/src/huddle/authoring/sdk.ts', import.meta.url);
const text = await huddleAuthoringTypes(root);
const source = await format(
  `// Generated by scripts/build-huddle-types.mjs; do not edit.\nexport const huddleSdkTypes = ${JSON.stringify(text)};\n`,
  { parser: 'typescript', singleQuote: true, printWidth: 100 },
);
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')) !== source)
    throw new Error('Huddle SDK types are stale; run node scripts/build-huddle-types.mjs');
} else await writeFile(target, source);

// Publish the exact formatter used by the IDE as ordinary editable TypeScript.
const promptTarget = new URL(
  '../packages/shared/src/huddle/templates/prompts/source.ts',
  import.meta.url,
);
const promptText = await readFile(
  new URL('../packages/shared/src/huddle/templates/prompts/format.ts', import.meta.url),
  'utf8',
);
const promptSource = await format(
  `// Generated by scripts/build-huddle-types.mjs; do not edit.\nexport const agentPromptSource = ${JSON.stringify(promptText)};\n`,
  { parser: 'typescript', singleQuote: true, printWidth: 100 },
);
if (process.argv.includes('--check')) {
  if ((await readFile(promptTarget, 'utf8')) !== promptSource)
    throw new Error('Huddle prompt source is stale; run node scripts/build-huddle-types.mjs');
} else await writeFile(promptTarget, promptSource);
