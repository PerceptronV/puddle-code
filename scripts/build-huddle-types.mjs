import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';
import { huddleAuthoringTypes } from './lib/huddle/types.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const target = new URL('../packages/shared/src/huddle/authoring/sdk.ts', import.meta.url);
const text = await huddleAuthoringTypes(root);
const source = await format(
  `// Generated by scripts/build-huddle-types.mjs; do not edit.\nexport const huddleSdkTypes = ${JSON.stringify(text)};\n`,
  { parser: 'typescript', singleQuote: true, printWidth: 100 },
);
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')) !== source)
    throw new Error('Huddle SDK types are stale; run node scripts/build-huddle-types.mjs');
} else await writeFile(target, source);
