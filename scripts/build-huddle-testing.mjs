import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';
import { huddleTestingFiles } from './lib/huddle/testing.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const target = new URL('../packages/shared/src/huddle/authoring/testing.ts', import.meta.url);
const files = await huddleTestingFiles(root);
const source = await format(
  `// Generated by scripts/build-huddle-testing.mjs; do not edit.\nexport const huddleTestingAssets: Record<string,string> = ${JSON.stringify(files)};\n`,
  { parser: 'typescript', singleQuote: true, printWidth: 100 },
);
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')) !== source)
    throw new Error('Huddle testing assets are stale; run node scripts/build-huddle-testing.mjs');
} else await writeFile(target, source);
